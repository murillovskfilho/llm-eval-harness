// Writes evals/logistics-support/SUMMARY.md from the result files. Every number is computed, never typed.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FLOW = process.argv[2] ?? "evals/logistics-support";
const state = JSON.parse(readFileSync(join(FLOW, "_state.json"), "utf8"));
const PRICES: Record<string, { in: number; out: number }> = state.prices;
const VARIANTS = [
  { id: "baseline", label: "Claude Haiku 5.5" },
  { id: "v1", label: "Claude Sonnet 5.5" },
];

type Row = {
  prompt_id: string; tags: string[]; status: string; grade: Record<string, number>;
  model: string; usage: Usage; judge_model?: string; judge_usage?: Usage; latency_s?: number;
};
type Usage = { input_tokens: number; output_tokens: number; cache_read_input_tokens?: number; cache_creation_input_tokens?: number };

const read = (f: string) => (existsSync(f) ? readFileSync(f, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l)) : []);
const cost = (model: string | undefined, u: Usage | undefined) => {
  const p = model && PRICES[Object.keys(PRICES).find((k) => model.startsWith(k)) ?? ""];
  if (!p || !u) return NaN;
  const input = u.input_tokens + 1.25 * (u.cache_creation_input_tokens ?? 0) + 0.1 * (u.cache_read_input_tokens ?? 0);
  return (input * p.in + u.output_tokens * p.out) / 1e6;
};
const pct = (x: number) => `${(x * 100).toFixed(0)}%`;
const ci = (p: number, n: number) => `±${(1.96 * Math.sqrt((p * (1 - p)) / n) * 100).toFixed(0)}`;
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
const median = (xs: number[]) => { const s = [...xs].sort((a, b) => a - b); return s[Math.floor(s.length / 2)]; };

const data = VARIANTS.map((v) => ({
  ...v,
  rows: read(join(FLOW, v.id, "results.jsonl")).filter((r: Row) => r.status === "ok") as Row[],
  errors: read(join(FLOW, v.id, "errors.jsonl")).length,
})).filter((v) => v.rows.length);

if (!data.length) {
  console.log("no results yet");
  process.exit(0);
}

const metrics: { id: string; label: string }[] = state.metrics;
const categories = [...new Set(data.flatMap((v) => v.rows.map((r) => r.tags[0])))];

let md = `# Results: delivery-support assistant\n\n`;
md += `${data[0].rows.length} cases, 1 rep each. Judge: Claude Opus 5.5. Generated by \`src/summary.ts\` from \`results.jsonl\`.\n\n`;
md += `| Model | ${metrics.map((m) => m.label).join(" | ")} | Median latency | Cost per run | Errors |\n|---|${metrics.map(() => "---").join("|")}|---|---|---|\n`;
for (const v of data) {
  const n = v.rows.length;
  const cells = metrics.map((m) => {
    const p = mean(v.rows.map((r) => r.grade[m.id]));
    return m.id === "pass" ? `**${pct(p)}** ${ci(p, n)}` : pct(p);
  });
  const sutCost = v.rows.reduce((s, r) => s + cost(r.model, r.usage), 0);
  const judgeCost = v.rows.reduce((s, r) => s + cost(r.judge_model, r.judge_usage), 0);
  const lat = median(v.rows.map((r) => r.latency_s ?? NaN).filter(Number.isFinite));
  md += `| ${v.label} | ${cells.join(" | ")} | ${Number.isFinite(lat) ? lat.toFixed(1) + " s" : "not measured"} | ${Number.isFinite(sutCost) ? "$" + sutCost.toFixed(4) : "not measured"} (+ judge ${Number.isFinite(judgeCost) ? "$" + judgeCost.toFixed(3) : "n/a"}) | ${v.errors} |\n`;
}

md += `\n## Pass rate by category\n\n| Category | Cases | ${data.map((v) => v.label).join(" | ")} |\n|---|---|${data.map(() => "---").join("|")}|\n`;
for (const c of categories) {
  const n = data[0].rows.filter((r) => r.tags[0] === c).length;
  md += `| ${c} | ${n} | ${data.map((v) => pct(mean(v.rows.filter((r) => r.tags[0] === c).map((r) => r.grade.pass)))).join(" | ")} |\n`;
}

if (data.length === 2) {
  const [a, b] = data;
  const byId = new Map(a.rows.map((r) => [r.prompt_id, r.grade.pass]));
  const flips = b.rows.filter((r) => byId.has(r.prompt_id) && byId.get(r.prompt_id) !== r.grade.pass);
  md += `\n## Cases where the two models disagree\n\n`;
  md += flips.length
    ? flips.map((r) => `- \`${r.prompt_id}\` (${r.tags[0]}): ${a.label} ${byId.get(r.prompt_id) ? "pass" : "fail"}, ${b.label} ${r.grade.pass ? "pass" : "fail"}`).join("\n") + "\n"
    : "None.\n";
  md += `\nWith ${a.rows.length} cases the 95% interval on a pass rate is about ±${(1.96 * Math.sqrt(0.25 / a.rows.length) * 100).toFixed(0)} points, so treat small gaps between the models as noise.\n`;
}

writeFileSync(join(FLOW, "SUMMARY.md"), md);
console.log(md);
